// Characters outside ASCII fall back to their closest plain letter.
var FALLBACK = {
    "Ç": "C", "Ğ": "G", "İ": "I", "ı": "I", "Ö": "O",
    "Ş": "S", "Ü": "U", "Ä": "A", "Å": "A", "É": "E",
    "È": "E", "Ê": "E", "Á": "A", "À": "A", "Í": "I",
    "Ó": "O", "Ú": "U", "Ñ": "N", "ß": "S", "Ł": "L",
    "Ż": "Z", "Ž": "Z", "Š": "S", "Č": "C", "Ř": "R",
    "Ø": "O", "Æ": "E", "…": ".", "–": "-", "—": "-",
    "×": "X", "•": "·"
}

function normalize(text) {
    var up = String(text).toUpperCase()
    var out = ""
    for (var i = 0; i < up.length; i++) {
        var c = up[i]
        if (GLYPHS[c] === undefined)
            c = FALLBACK[c] !== undefined ? FALLBACK[c] : "?"
        out += c
    }
    return out
}

function glyph(c) {
    return GLYPHS[c] || GLYPHS["?"]
}

// Width in font pixels (one column of spacing between glyphs).
function width(text) {
    var n = normalize(text).length
    return n > 0 ? n * (W + 1) - 1 : 0
}
